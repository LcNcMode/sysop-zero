#!/usr/bin/env python3
"""Generate .github/CODEOWNERS from the `maintainers` field of every prods/*/prod.yaml.

  python3 scripts/gen_codeowners.py          # write .github/CODEOWNERS
  python3 scripts/gen_codeowners.py --check  # exit 1 if the file is out of date (used by CI)

Handles are scene names and cannot be resolved to GitHub accounts, so ownership
comes from the optional `maintainers` list (GitHub logins). A prod without
maintainers gets a commented line naming its handles, so the gap stays visible.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".github/CODEOWNERS"
HEADER = """# GENERATED by scripts/gen_codeowners.py from prods/*/prod.yaml (`maintainers`).
# Do not edit by hand: change prod.yaml and run the script. CI checks that this is in sync.
#
# Repo-level paths (.github/, scripts/, site/, docs/, engines/) are protected by the
# ruleset on main (see scripts/setup-repo.sh); add owners here once the repo has a team.
"""


def render() -> str:
    lines = [HEADER]
    for y in sorted((ROOT / "prods").glob("*/prod.yaml")):
        d = yaml.safe_load(y.read_text(encoding="utf-8")) or {}
        folder = f"/prods/{y.parent.name}/"
        owners = " ".join(f"@{m}" for m in d.get("maintainers") or [])
        if owners:
            lines.append(f"{folder} {owners}")
        else:
            lines.append(f"# {folder} — no maintainers declared (handles: {', '.join(d.get('handles') or [])})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    new = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != new:
            print("CODEOWNERS is out of date: run python3 scripts/gen_codeowners.py", file=sys.stderr)
            sys.exit(1)
        print("CODEOWNERS is in sync")
    else:
        OUT.write_text(new, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
